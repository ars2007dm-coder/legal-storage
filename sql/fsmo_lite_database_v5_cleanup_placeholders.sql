-- =====================================================================
-- Необязательный скрипт: удаляет очевидные тестовые/заглушечные
-- записи в videos (например "Профессор Иванов" и подобные учебные
-- заглушки). Выполните ОТДЕЛЬНО, посмотрите на результат SELECT
-- перед тем как удалять — чтобы случайно не стереть настоящие видео.
-- =====================================================================

-- Сначала посмотреть, что удалится:
SELECT id, title, teacher_name FROM videos
WHERE teacher_name ILIKE '%иванов%'
   OR teacher_name ILIKE '%тест%'
   OR title ILIKE '%тест%'
   OR title ILIKE '%example%'
   OR title ILIKE '%пример%';

