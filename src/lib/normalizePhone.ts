// Приводит номер телефона к последним 10 цифрам, чтобы сравнивать
// номера, введённые в разных форматах (+7 916 123-45-67, 89161234567,
// 79161234567 и т.п. — все дают "9161234567"). Используется, чтобы
// сопоставить номер из обычного входа (личный кабинет) с номером,
// введённым отдельно при заявке на доступ к ДЗ.

export function normalizePhone(raw: string | null | undefined): string {
  if (!raw) return ''
  const digits = raw.replace(/\D/g, '')
  return digits.slice(-10)
}
